function asstHandleFile(file){
  const A = state.assistant.audio;
  A.name = file.name;
  if (file.size > 15 * 1024 * 1024){
    A.error = 'Tệp quá lớn (' + Math.round(file.size / 1048576) + ' MB). Giới hạn khoảng 15 MB — hãy cắt ngắn đoạn âm thanh rồi thử lại.';
    A.result = null; A.busy = false; labiRender(); return;
  }
  A.error = null; A.result = null; A.busy = true;
  labiRender();
  const reader = new FileReader();
  reader.onload = () => {
    const dataUrl = String(reader.result || '');
    const comma = dataUrl.indexOf(',');
    const b64 = comma >= 0 ? dataUrl.slice(comma + 1) : dataUrl;
    Translate.analyzeAudio(b64, file.type || 'audio/mpeg', (res, err) => {
      A.busy = false;
      if (err || !res) A.error = asstErrMsg(err || 'no-server');
      else if (res.error) A.error = asstErrMsg(res.error);
      else {
        A.result = res; A.lang = res.lang || ''; A.error = null; A.editing = false; A.showVi = false;
        // câu có thể sửa được: mỗi câu = { ko, vi }
        A.segments = (res.sentences || []).map(s => ({
          ko: (s.text && s.text.trim()) ? s.text.trim()
              : (s.words || []).map(w => w.w).join(' '),
          vi: s.vi || ''
        })).filter(s => s.ko);
        // bản đồ nghĩa từng từ (để tra nhanh + nút thêm vào từ điển)
        A.glossMap = {};
        (res.sentences || []).forEach(s => (s.words || []).forEach(w => {
          if (w.w && !A.glossMap[w.w]) A.glossMap[w.w] = { rom: w.rom || '', vi: w.vi || '' };
        }));
      }
      if (state.labiOpen) labiRender();
    });
  };
  reader.onerror = () => { A.busy = false; A.error = 'Không đọc được tệp âm thanh.'; labiRender(); };
  reader.readAsDataURL(file);
}

