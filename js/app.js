/* ============================================================
   LABI — trợ lý ngôn ngữ (cửa sổ nổi): hỏi đáp + phân tích tệp âm thanh
   ============================================================ */
function mdLite(s){
  let t = esc(String(s));
  t = t.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>');
  t = t.replace(/`([^`]+)`/g, '<code>$1</code>');
  t = t.replace(/\n/g, '<br>');
  return t;
}
